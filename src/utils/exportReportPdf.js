/** Creates a PDF file from the same report data shown in the interface. */
export async function buildReportPdfBytes({ userName, report, streak, fontBytes, now = new Date() }) {
  const [{ PDFDocument, rgb }, { default: fontkit }] = await Promise.all([
    import('pdf-lib'), import('@pdf-lib/fontkit'),
  ]);
  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  const font = await pdf.embedFont(fontBytes);
  const supported = new Set(font.getCharacterSet());
  const clean = (value) => Array.from(String(value ?? '')).map((c) =>
    supported.has(c.codePointAt(0)) ? c : '?').join('');
  pdf.setTitle('Acad Learning Report');
  pdf.setAuthor('Acad');
  pdf.setCreationDate(now);
  let page;
  let y;
  function newPage() { page = pdf.addPage([595.28, 841.89]); y = 790; }
  newPage();
  function line(value, size = 11, color = rgb(0.1, 0.13, 0.16)) {
    const words = clean(value).replace(/\s+/g, ' ').trim().split(' ');
    let current = '';
    const width = 487;
    function draw(text) {
      if (y < 60) newPage();
      page.drawText(text, { x: 54, y, size, font, color });
      y -= size * 1.45;
    }
    for (const word of words) {
      if (font.widthOfTextAtSize(word, size) > width) {
        if (current) draw(current);
        let part = '';
        for (const char of word) {
          if (font.widthOfTextAtSize(part + char, size) > width) { draw(part); part = ''; }
          part += char;
        }
        current = part;
      } else if (current && font.widthOfTextAtSize(`${current} ${word}`, size) > width) {
        draw(current); current = word;
      } else current = current ? `${current} ${word}` : word;
    }
    if (current) draw(current);
  }
  function heading(title) {
    if (y < 110) newPage();
    y -= 14;
    line(title, 14, rgb(0, 0.35, 0.32));
    y -= 4;
  }
  const { kpis, summary, priorityTopics, courseRows, actions, recall } = report;
  line('Acad Learning Report', 22);
  line(`${userName || 'Member'} · ${now.toLocaleDateString('en-GB')} · ${streak?.current ?? 0}-day streak`, 10);
  heading('Acad insights');
  line(summary || 'No summary available yet.');
  line('Rule-based summary. Mastery values reflect recorded self-assessment.', 9);
  heading('Snapshot');
  line(`Cards due: ${kpis.dueCards} | Topics below 60%: ${kpis.weakTopics}`);
  line(`Average topic mastery: ${kpis.avgMastery}% | Total study logged: ${Number(kpis.totalStudyHours ?? 0).toFixed(1)}h`);
  heading('Recommended next steps');
  if (!actions.length) line('No recommendations available yet.');
  actions.forEach((a) => line(`${a.priority}: ${a.text}`));
  heading('Priority topics');
  if (!priorityTopics.length) line('No priority topics recorded.');
  priorityTopics.forEach((t) => {
    line(`${t.courseCode} · ${t.name} · ${t.masteryLevel}%`);
    line(`Last studied: ${t.lastStudied ? new Date(t.lastStudied).toLocaleDateString('en-GB') : 'Never'}`, 9);
  });
  heading('Recall pipeline');
  line(`Due: ${recall.due} | Learning: ${recall.learning} | Reviewing: ${recall.reviewing} | Mastered: ${recall.mastered}`);
  heading('By course');
  if (!courseRows.length) line('No courses recorded.');
  courseRows.forEach((c) => line(`${c.code} · ${c.name} · ${c.avg}% · ${c.below60} topic(s) below 60%`));
  const pages = pdf.getPages();
  pages.forEach((p, i) => p.drawText(`Generated by Acad · Current device report · Page ${i + 1} of ${pages.length}`, {
    x: 54, y: 30, size: 8, font, color: rgb(0.35, 0.35, 0.35),
  }));
  return pdf.save();
}

export async function exportReportPdf(input) {
  const fontResponse = await fetch(new URL('../assets/fonts/DejaVuSans.ttf', import.meta.url));
  if (!fontResponse.ok) throw new Error('Could not load the report font. Please try again.');
  const fontBytes = new Uint8Array(await fontResponse.arrayBuffer());
  const bytes = await buildReportPdfBytes({ ...input, fontBytes });
  const url = URL.createObjectURL(new Blob([bytes], { type: 'application/pdf' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = `Acad_Learning_Report_${new Date().toISOString().slice(0, 10)}.pdf`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 60000);
  return true;
}
